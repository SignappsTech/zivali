#!/usr/bin/env node
// Design token generator and contrast linter. No dependencies.
//
//   node docs/design/build-tokens.mjs            writes tokens.css, directions/tailwind-config.js, directions/resolved.json; checks contrast
//   node docs/design/build-tokens.mjs --report   also prints markdown contrast tables
//
// Source of truth: docs/design/tokens.json. The tech-lead replaces this with packages/tokens;
// the resolve and contrast logic below is the reference behaviour.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));
const report = process.argv.includes('--report');

// ---------- colour maths ----------
const hex2rgb = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16));
const lin = c => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = hex => { const [r, g, b] = hex2rgb(hex).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
function hex2hsl(hex) {
  const [r, g, b] = hex2rgb(hex).map(v => v / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  let h = 0, s = 0; const l = (max + min) / 2;
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1));
    if (max === r) h = ((g - b) / d) % 6; else if (max === g) h = (b - r) / d + 2; else h = (r - g) / d + 4;
    h *= 60; if (h < 0) h += 360;
  }
  const f = n => Math.round(n * 10) / 10;
  return `${f(h)} ${f(s * 100)}% ${f(l * 100)}%`;
}

// ---------- resolve ----------
const prim = T.primitives.color;
function resolveRef(ref) {
  if (ref.startsWith('#')) return ref.toUpperCase();
  const [scale, step = 'DEFAULT'] = ref.split('.');
  const v = prim[scale]?.[step];
  if (!v) throw new Error(`Unknown colour ref "${ref}"`);
  return v.toUpperCase();
}
const resolve = v => typeof v === 'string' ? { hex: resolveRef(v) } : { hex: resolveRef(v.ref), alpha: v.alpha };
const tokensFor = mode => Object.fromEntries(Object.entries(T.semantic[mode]).map(([k, v]) => [k, resolve(v)]));

// ---------- lint ----------
let failures = 0;
const rows = [];
for (const mode of ['light', 'dark']) {
  const tk = tokensFor(mode);
  for (const [fg, bg, min] of T.pairs.list) {
    if (!tk[fg] || !tk[bg]) { console.error(`MISSING token in pair ${fg}/${bg} (${mode})`); failures++; continue; }
    const r = ratio(tk[fg].hex, tk[bg].hex);
    const ok = r + 1e-9 >= min;
    rows.push({ mode, fg, bg, min, r, ok });
    if (!ok) { failures++; console.error(`FAIL ${mode}: ${fg} on ${bg} = ${r.toFixed(2)} (min ${min})`); }
  }
}

// ---------- tokens.css ----------
const radiusExpr = k => ({ sm: 'calc(var(--radius) - 4px)', md: 'calc(var(--radius) - 2px)', lg: 'var(--radius)', xl: 'calc(var(--radius) + 4px)', '2xl': 'calc(var(--radius) + 8px)', full: '9999px' }[k] || k);
const shapeLines = () => [
  `  --radius: ${T.shape.radius};`,
  `  --font-display: ${T.primitives.fontFamily.display};`,
  `  --font-sans: ${T.primitives.fontFamily.sans};`,
  ...Object.entries(T.shape).filter(([k]) => !['radius', 'note'].includes(k)).map(([k, v]) => `  --radius-${k}: ${radiusExpr(v)};`),
  `  --card-shadow: none;`
];
const elevLines = mode => Object.entries(T.elevation[mode]).map(([k, v]) => `  --${k}: ${v};`);
function block(selector, tk, extra) {
  const lines = [];
  for (const [k, v] of Object.entries(tk)) {
    lines.push(`  --${k}: ${hex2hsl(v.hex)};`);
    if (v.alpha !== undefined) lines.push(`  --${k}-alpha: ${v.alpha};`);
  }
  return `${selector} {\n${[...lines, ...extra].join('\n')}\n}\n`;
}
let css = `/* GENERATED by docs/design/build-tokens.mjs from docs/design/tokens.json. Do not edit by hand.
   Colours are HSL triplets: use hsl(var(--token)) or hsl(var(--token) / <alpha>).
   Dark mode: add the .dark class to an ancestor. Use .light inside a .dark scope to force light tokens. */\n\n`;
css += block(':root, .light', tokensFor('light'), [...shapeLines(), ...elevLines('light')]);
css += '\n' + block('.dark', tokensFor('dark'), elevLines('dark'));
fs.writeFileSync(path.join(here, 'tokens.css'), css);

// ---------- tailwind config for the Play CDN mockups (stand-in for the real preset) ----------
const colors = {};
for (const n of Object.keys(T.semantic.light)) colors[n] = `hsl(var(--${n}) / <alpha-value>)`;
const twc = {
  darkMode: 'class',
  theme: { extend: {
    colors,
    borderRadius: { sm: 'calc(var(--radius) - 4px)', md: 'calc(var(--radius) - 2px)', lg: 'var(--radius)', xl: 'calc(var(--radius) + 4px)', '2xl': 'calc(var(--radius) + 8px)', '3xl': 'calc(var(--radius) + 16px)' },
    fontFamily: { display: ['var(--font-display)'], sans: ['var(--font-sans)'] },
    boxShadow: { sm: 'var(--shadow-sm)', md: 'var(--shadow-md)', lg: 'var(--shadow-lg)', pop: 'var(--shadow-pop)' },
    fontSize: Object.fromEntries(Object.entries(T.scale.type.size).map(([k, v]) => [k, [`${v.px / 16}rem`, `${v.line / 16}rem`]])),
    minHeight: { touch: '44px', comfort: '48px', primary: '56px' },
    minWidth: { touch: '44px', comfort: '48px' }
  } }
};
fs.mkdirSync(path.join(here, 'directions'), { recursive: true });
fs.writeFileSync(path.join(here, 'directions', 'tailwind-config.js'),
  `/* GENERATED by docs/design/build-tokens.mjs. Stand-in for the packages/tokens Tailwind preset, used by the static direction mockups. */\ntailwind.config = ${JSON.stringify(twc, null, 2)};\n`);

// ---------- resolved hex (used by the mockup builder and the docs) ----------
const resolved = {};
for (const mode of ['light', 'dark']) resolved[mode] = Object.fromEntries(Object.entries(tokensFor(mode)).map(([k, v]) => [k, v.hex]));
fs.writeFileSync(path.join(here, 'directions', 'resolved.json'), JSON.stringify(resolved, null, 1));

if (report) {
  for (const mode of ['light', 'dark']) {
    console.log(`\n${mode}\n| Pair | Hex | Ratio | Need |\n|---|---|---|---|`);
    const tk = tokensFor(mode);
    for (const r of rows.filter(x => x.mode === mode)) console.log(`| \`${r.fg}\` on \`${r.bg}\` | ${tk[r.fg].hex} on ${tk[r.bg].hex} | ${r.r.toFixed(1)}:1 | ${r.min}:1 |`);
  }
}
console.log(failures ? `\n${failures} contrast failure(s)` : `\nAll ${rows.length} pair checks pass (AA floor, AAA where declared).`);
process.exit(failures ? 1 : 0);
