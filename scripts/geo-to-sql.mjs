// Generates plain SQL that loads the GURS geo reference data (12 statistical regions, 212 municipalities)
// from supabase/seed/geo/*.geojson into public.regions and public.municipalities (C6, ADR-006).
// Output is deterministic: rows sorted by id, coordinates copied as-is, geometry as EWKT literals.
// Usage: node scripts/geo-to-sql.mjs <out.sql>
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const GEO_DIR = new URL('../supabase/seed/geo/', import.meta.url);

export const loadFeatures = (name) => JSON.parse(readFileSync(new URL(`${name}.geojson`, GEO_DIR), 'utf8')).features;

const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;

const integer = (v, what) => {
	if (!Number.isInteger(v)) throw new Error(`${what}: expected an integer, got ${JSON.stringify(v)}`);
	return String(v);
};

const text = (v, what) => {
	if (typeof v !== 'string' || v.trim() === '') throw new Error(`${what}: expected text`);
	return quote(v);
};

const slug = (v, what) => {
	if (typeof v !== 'string' || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(v)) {
		throw new Error(`${what}: invalid slug ${JSON.stringify(v)}`);
	}
	return quote(v);
};

const ewkt = ({ type, coordinates }, what) => {
	if (type !== 'Polygon' && type !== 'MultiPolygon') throw new Error(`${what}: unsupported ${type}`);
	const polygons = type === 'Polygon' ? [coordinates] : coordinates;
	const ring = (r) => `(${r.map(([lng, lat]) => `${lng} ${lat}`).join(',')})`;
	return quote(`SRID=4326;MULTIPOLYGON(${polygons.map((p) => `(${p.map(ring).join(',')})`).join(',')})`);
};

const insert = (table, columns, features) => {
	const rows = [...features]
		.sort((a, b) => a.properties.id - b.properties.id)
		.map((f) => {
			const p = f.properties;
			const what = `${table} ${p.id}`;
			const values = columns.map((c) => {
				if (c === 'geom') return ewkt(f.geometry, what);
				if (c === 'slug') return slug(p.slug, what);
				if (c === 'id' || c === 'region_id') return integer(p[c], `${what} ${c}`);
				return text(p[c], `${what} ${c}`);
			});
			return `  (${values.join(', ')})`;
		});
	const updates = columns
		.filter((c) => c !== 'id')
		.map((c) => `${c} = excluded.${c}`)
		.join(', ');
	return (
		`insert into public.${table} (${columns.join(', ')}) values\n${rows.join(',\n')}\n` +
		`on conflict (id) do update set ${updates};\n`
	);
};

export const geoToSql = (regions, municipalities) =>
	[
		'-- Generated by scripts/geo-to-sql.mjs from supabase/seed/geo/*.geojson. Do not edit; regenerate.',
		'-- Data: Geodetska uprava Republike Slovenije, Register prostorskih enot (CC BY 4.0), simplified.',
		'-- Licence, attribution and processing: supabase/seed/geo/LICENSE.md',
		'',
		insert('regions', ['id', 'slug', 'name_sl', 'name_en', 'geom'], regions),
		insert('municipalities', ['id', 'slug', 'name_sl', 'name_en', 'region_id', 'geom'], municipalities),
	].join('\n');

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	const out = process.argv[2];
	if (!out) {
		console.error('Usage: node scripts/geo-to-sql.mjs <out.sql>');
		process.exit(2);
	}
	writeFileSync(out, geoToSql(loadFeatures('regions'), loadFeatures('municipalities')));
	console.log(`Wrote ${out}`);
}
